/// A grid drawn at one pixel a cell (mirrored if `flip`): a canvas to make a texture of (with NearestFilter).
export function pixelCanvas(rows, { flip = false, palette = PALETTE } = {}) {
  const h = rows.length, w = Math.max(...rows.map((r) => r.length));
  const c = document.createElement("canvas");
  c.width = w;
  c.height = h;
  const g = c.getContext("2d");
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      const col = palette[r[x]];
      if (!col) continue;
      g.fillStyle = col;
      g.fillRect(flip ? w - 1 - x : x, y, 1, 1);
    }
  });
  return c;
}
